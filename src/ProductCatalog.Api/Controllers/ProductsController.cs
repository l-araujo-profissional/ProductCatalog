using Microsoft.AspNetCore.Mvc;
using ProductCatalog.Api.Application;
using ProductCatalog.Api.Contracts;

namespace ProductCatalog.Api.Controllers;

/// <summary>
/// HTTP layer for products. Controllers stay deliberately thin: they only bind input, call
/// <see cref="IProductService"/> and shape the HTTP result. Errors are thrown as exceptions and
/// converted to ProblemDetails by the global exception handler.
/// </summary>
/// <param name="service">Application service holding the business rules.</param>
[ApiController]
[Route("api/products")]
[Produces("application/json")]
public class ProductsController(IProductService service) : ControllerBase
{
    /// <summary>Lists all products, including their available stock.</summary>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">The list of products (possibly empty).</response>
    [HttpGet]
    [ProducesResponseType(typeof(IReadOnlyList<ProductResponse>), StatusCodes.Status200OK)]
    public async Task<ActionResult<IReadOnlyList<ProductResponse>>> GetAll(CancellationToken ct)
        => Ok(await service.GetAllAsync(ct));

    // Literal routes (search, stock-level) win over "{id:int}" and the int constraint avoids any ambiguity.

    /// <summary>Searches products by name using a partial, case-insensitive match.</summary>
    /// <param name="name">Text the product name must contain.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">Matching products (possibly empty).</response>
    /// <response code="400">The name is missing or blank.</response>
    [HttpGet("search")]
    [ProducesResponseType(typeof(IReadOnlyList<ProductResponse>), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status400BadRequest)]
    public async Task<ActionResult<IReadOnlyList<ProductResponse>>> Search([FromQuery] string name, CancellationToken ct)
        => Ok(await service.SearchByNameAsync(name, ct));

    /// <summary>Returns products whose stock is within an inclusive range.</summary>
    /// <param name="min">Lowest stock to include (default 0).</param>
    /// <param name="max">Highest stock to include (default: no upper limit).</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">Products within the range (possibly empty).</response>
    /// <response code="400">A bound is negative or min is greater than max.</response>
    [HttpGet("stock-level")]
    [ProducesResponseType(typeof(IReadOnlyList<ProductResponse>), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status400BadRequest)]
    public async Task<ActionResult<IReadOnlyList<ProductResponse>>> GetByStockLevel(
        [FromQuery] int min = 0, [FromQuery] int max = int.MaxValue, CancellationToken ct = default)
        => Ok(await service.GetByStockLevelAsync(min, max, ct));

    /// <summary>Gets a single product by its six-digit id.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">The product.</response>
    /// <response code="404">No product has this id.</response>
    [HttpGet("{id:int}")]
    [ProducesResponseType(typeof(ProductResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    public async Task<ActionResult<ProductResponse>> GetById(int id, CancellationToken ct)
        => Ok(await service.GetByIdAsync(id, ct));

    /// <summary>Creates a product. The id is generated by the server.</summary>
    /// <param name="request">Product data.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="201">The created product; the Location header points to it.</response>
    /// <response code="400">Validation failed (missing or invalid fields).</response>
    [HttpPost]
    [ProducesResponseType(typeof(ProductResponse), StatusCodes.Status201Created)]
    [ProducesResponseType(typeof(ValidationProblemDetails), StatusCodes.Status400BadRequest)]
    public async Task<ActionResult<ProductResponse>> Create([FromBody] ProductRequest request, CancellationToken ct)
    {
        var created = await service.CreateAsync(request, ct);

        // 201 Created + Location header (/api/products/{id}) is the REST convention for creation.
        return CreatedAtAction(nameof(GetById), new { id = created.Id }, created);
    }

    /// <summary>Replaces all editable fields of an existing product.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="request">New product data.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">The updated product.</response>
    /// <response code="400">Validation failed.</response>
    /// <response code="404">No product has this id.</response>
    /// <response code="409">The product was modified concurrently by another request.</response>
    [HttpPut("{id:int}")]
    [ProducesResponseType(typeof(ProductResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ValidationProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status409Conflict)]
    public async Task<ActionResult<ProductResponse>> Update(int id, [FromBody] ProductRequest request, CancellationToken ct)
        => Ok(await service.UpdateAsync(id, request, ct));

    /// <summary>Deletes a product.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="204">The product was deleted.</response>
    /// <response code="404">No product has this id.</response>
    [HttpDelete("{id:int}")]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    public async Task<IActionResult> Delete(int id, CancellationToken ct)
    {
        await service.DeleteAsync(id, ct);
        return NoContent();
    }

    /// <summary>Decrements a product's stock by the given quantity.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="quantity">Units to remove; must be greater than zero.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">The product with its updated stock.</response>
    /// <response code="400">The quantity is not positive.</response>
    /// <response code="404">No product has this id.</response>
    /// <response code="409">There is not enough stock.</response>
    [HttpPost("{id:int}/decrement-stock/{quantity:int}")]
    [ProducesResponseType(typeof(ProductResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status409Conflict)]
    public async Task<ActionResult<ProductResponse>> DecrementStock(int id, int quantity, CancellationToken ct)
        => Ok(await service.DecrementStockAsync(id, quantity, ct));

    /// <summary>Increments a product's stock by the given quantity.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="quantity">Units to add; must be greater than zero.</param>
    /// <param name="ct">Cancelled automatically if the client disconnects.</param>
    /// <response code="200">The product with its updated stock.</response>
    /// <response code="400">The quantity is not positive.</response>
    /// <response code="404">No product has this id.</response>
    /// <response code="409">The new stock would exceed the maximum supported value.</response>
    [HttpPost("{id:int}/add-to-stock/{quantity:int}")]
    [ProducesResponseType(typeof(ProductResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status409Conflict)]
    public async Task<ActionResult<ProductResponse>> AddToStock(int id, int quantity, CancellationToken ct)
        => Ok(await service.AddToStockAsync(id, quantity, ct));
}
