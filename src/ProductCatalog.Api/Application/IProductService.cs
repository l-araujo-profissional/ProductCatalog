using ProductCatalog.Api.Contracts;

namespace ProductCatalog.Api.Application;

/// <summary>
/// Application-level operations on products. Implementations enforce business rules and
/// signal failures with <see cref="Domain.AppException"/> subclasses.
/// </summary>
public interface IProductService
{
    /// <summary>Returns all products, ordered by id.</summary>
    /// <param name="ct">Token to cancel the operation.</param>
    Task<IReadOnlyList<ProductResponse>> GetAllAsync(CancellationToken ct = default);

    /// <summary>Returns one product.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.NotFoundException">The product does not exist.</exception>
    Task<ProductResponse> GetByIdAsync(int id, CancellationToken ct = default);

    /// <summary>Creates a product; the id is generated by the database.</summary>
    /// <param name="request">Validated product data.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    Task<ProductResponse> CreateAsync(ProductRequest request, CancellationToken ct = default);

    /// <summary>Replaces all editable fields of an existing product.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="request">Validated product data, optionally with the <c>RowVersion</c> last read.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.BadRequestException">The <c>RowVersion</c> is not a valid token.</exception>
    /// <exception cref="Domain.NotFoundException">The product does not exist.</exception>
    Task<ProductResponse> UpdateAsync(int id, ProductRequest request, CancellationToken ct = default);

    /// <summary>Deletes a product.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.NotFoundException">The product does not exist.</exception>
    Task DeleteAsync(int id, CancellationToken ct = default);

    /// <summary>Removes <paramref name="quantity"/> units from a product's stock.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="quantity">Units to remove; must be greater than zero.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.BadRequestException">The quantity is not positive.</exception>
    /// <exception cref="Domain.NotFoundException">The product does not exist.</exception>
    /// <exception cref="Domain.ConflictException">There is not enough stock.</exception>
    Task<ProductResponse> DecrementStockAsync(int id, int quantity, CancellationToken ct = default);

    /// <summary>Adds <paramref name="quantity"/> units to a product's stock.</summary>
    /// <param name="id">Product identifier.</param>
    /// <param name="quantity">Units to add; must be greater than zero.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.BadRequestException">The quantity is not positive.</exception>
    /// <exception cref="Domain.NotFoundException">The product does not exist.</exception>
    /// <exception cref="Domain.ConflictException">The new stock would overflow.</exception>
    Task<ProductResponse> AddToStockAsync(int id, int quantity, CancellationToken ct = default);

    /// <summary>Finds products whose name contains the given text (partial, case-insensitive match).</summary>
    /// <param name="name">Text to look for; must not be blank.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.BadRequestException">The name is blank.</exception>
    Task<IReadOnlyList<ProductResponse>> SearchByNameAsync(string name, CancellationToken ct = default);

    /// <summary>Returns products whose stock lies in the inclusive range [<paramref name="min"/>, <paramref name="max"/>].</summary>
    /// <param name="min">Lowest stock to include; zero or greater.</param>
    /// <param name="max">Highest stock to include; must be at least <paramref name="min"/>.</param>
    /// <param name="ct">Token to cancel the operation.</param>
    /// <exception cref="Domain.BadRequestException">The range is invalid.</exception>
    Task<IReadOnlyList<ProductResponse>> GetByStockLevelAsync(int min, int max, CancellationToken ct = default);
}
